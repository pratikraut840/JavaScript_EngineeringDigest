// ==================================================
// Data Types in JavaScript
// ==================================================

// Number
let num1 = 10;
console.log(num1);

// String
let s1 = "India";
console.log(s1);

let s2 = 'Australia';
console.log(s2);

let s3 = `America`;
console.log(s3);

// Boolean
let isSunday = true;
console.log(isSunday);

// Object
let user = {
    name: 'Pratik',
    company: 'Impetus',
    language: 'English'
};
console.log(user);

// Array
let array1 = [1, 2, 3, 4];
console.log(array1);

// Null
let phone = null;
console.log(phone);

// Undefined
let mobile;
console.log(mobile);

// BigInt
let int1 = 23835435983457345343454n; // 'n' suffix denotes BigInt
console.log(int1);

// Debugger statement (pauses execution in dev tools)
debugger;
