// ==================================================
// Variables in JavaScript
// ==================================================

// --------------------
// var
// --------------------
// Can be redeclared and reassigned

var a = 10; // declare
var a = 20; // redeclare
a = 30;     // reassign
console.log(a);

// --------------------
// let
// --------------------
// Cannot be redeclared, but can be reassigned

let b = 44;
b = 45; // reassign
console.log(b);

// --------------------
// const
// --------------------
// Cannot be redeclared or reassigned

const c = 90; // declare
console.log(c);
