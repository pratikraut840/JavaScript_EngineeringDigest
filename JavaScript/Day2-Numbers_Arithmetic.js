// ==================================================
// Arithmetic Operators in JavaScript
// ==================================================

let a = 100;
let b = 300;

// Addition
let c = a + b;
console.log(c);

// Subtraction
let d = a - b;
console.log(d);

// Multiplication
let e = a * b;
console.log(e);

// Division
let f = a / b;
console.log(f);

// Modulus (remainder)
let g = a % b;
console.log(g);
